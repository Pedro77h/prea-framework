package database

import (
	"reflect"
	"strings"
	"testing"
)

type team struct {
	ID   int64  `pk:"" generated:"auto_increment"`
	Name string `size:"80" unique:""`
}

func (team) Table() string { return "app.teams" }

type player struct {
	ID       string  `pk:"" generated:"uuid"`
	TeamID   *int64  `fk:"app.teams" ondelete:"cascade" index:""`
	First    string  `unique:"full_name"`
	Last     string  `unique:"full_name" default:"o'neil"`
	MentorID *string `fk:"players"`
	Rev      int64   `version:""`
}

func (player) Table() string { return "players" }

func schemasOf(t *testing.T, types ...reflect.Type) []*table {
	t.Helper()
	tables := make([]*table, len(types))
	for i, typ := range types {
		s, err := schemaOf(typ)
		if err != nil {
			t.Fatal(err)
		}
		tables[i] = s
	}
	return tables
}

func TestDDL(t *testing.T) {
	sorted, err := ordered(schemasOf(t, reflect.TypeFor[player](), reflect.TypeFor[team]()))
	if err != nil {
		t.Fatal(err)
	}
	got := strings.Join(ddl(sorted), ";\n")
	want := `create schema if not exists "app";
create table if not exists "app"."teams" (
	"id" int8 generated by default as identity not null,
	"name" varchar(80) not null,
	primary key ("id")
);
alter table "app"."teams" add column if not exists "id" int8 generated by default as identity not null;
alter table "app"."teams" add column if not exists "name" varchar(80) not null;
create unique index if not exists "teams_name_key" on "app"."teams" ("name");
create table if not exists "players" (
	"id" uuid not null default gen_random_uuid(),
	"team_id" int8 references "app"."teams" on delete cascade,
	"first" text not null,
	"last" text not null default 'o''neil',
	"mentor_id" text references "players",
	"rev" int8 not null default 0,
	primary key ("id")
);
alter table "players" add column if not exists "id" uuid not null default gen_random_uuid();
alter table "players" add column if not exists "team_id" int8 references "app"."teams" on delete cascade;
alter table "players" add column if not exists "first" text not null;
alter table "players" add column if not exists "last" text not null default 'o''neil';
alter table "players" add column if not exists "mentor_id" text references "players";
alter table "players" add column if not exists "rev" int8 not null default 0;
create unique index if not exists "players_full_name_key" on "players" ("first", "last");
create index if not exists "players_team_id_idx" on "players" ("team_id")`
	if got != want {
		t.Fatalf("got\n%s\n\nwant\n%s", got, want)
	}

	if got := strings.Join(drops(sorted), "; "); got != `drop table if exists "players" cascade; drop table if exists "app"."teams" cascade` {
		t.Fatalf("drops: %s", got)
	}
}

type (
	cycleA struct {
		ID int64
		B  int64 `fk:"cycle_b"`
	}
	cycleB struct {
		ID int64
		A  int64 `fk:"cycle_a"`
	}
	orphan struct {
		ID     int64
		TeamID int64 `fk:"nowhere"`
	}
	toComposite struct {
		ID     int64
		Member int64 `fk:"memberships"`
	}
)

func (cycleA) Table() string      { return "cycle_a" }
func (cycleB) Table() string      { return "cycle_b" }
func (orphan) Table() string      { return "orphans" }
func (toComposite) Table() string { return "to_composite" }

func TestOrderedErrors(t *testing.T) {
	for want, types := range map[string][]reflect.Type{
		"foreign key cycle: cycle_a -> cycle_b -> cycle_a":      {reflect.TypeFor[cycleA](), reflect.TypeFor[cycleB]()},
		`fk:"nowhere" is not the table of a repository's model`: {reflect.TypeFor[orphan]()},
		`fk:"memberships" has a composite key`:                  {reflect.TypeFor[toComposite](), reflect.TypeFor[membership]()},
	} {
		if _, err := ordered(schemasOf(t, types...)); err == nil || !strings.Contains(err.Error(), want) {
			t.Errorf("got %v, want %q", err, want)
		}
	}
}

type (
	playerRepo  struct{ BaseRepository[player] }
	teamRepo    struct{ BaseRepository[team] }
	otherTeams  struct{ BaseRepository[otherTeam] }
	invalidRepo struct{ BaseRepository[noKey] }
	otherTeam   struct{ ID int64 }
)

func (otherTeam) Table() string { return "app.teams" }

// Without a database: the checks every mode runs before touching it.
func TestSyncSchemaChecks(t *testing.T) {
	ctx := t.Context()
	repos := []any{&playerRepo{}, &teamRepo{}, &teamRepo{}, "not a repository"}
	for _, mode := range []string{"", SchemaNone} {
		drop, err := SyncSchema(ctx, mode, repos)
		if err != nil || drop(ctx) != nil {
			t.Fatalf("mode %q: %v", mode, err)
		}
	}
	for _, tc := range []struct {
		mode  string
		comps []any
		want  string
	}{
		{"banana", repos, `schema "banana" is not none, validate`},
		{SchemaNone, []any{&invalidRepo{}}, "no primary key"},
		{SchemaValidate, []any{&teamRepo{}, &otherTeams{}}, "table app.teams is mapped by database.team and database.otherTeam"},
		{SchemaValidate, []any{&playerRepo{}}, `fk:"app.teams" is not the table of a repository's model`},
	} {
		if _, err := SyncSchema(ctx, tc.mode, tc.comps); err == nil || !strings.Contains(err.Error(), tc.want) {
			t.Errorf("%s: got %v, want %q", tc.mode, err, tc.want)
		}
	}
}
